param([switch]$SkipInstall)
$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot
$env:PYTHONUTF8 = '1'
$env:PYTHONIOENCODING = 'utf-8'
$python = Join-Path $PSScriptRoot '.venv\Scripts\python.exe'
if (-not (Test-Path -LiteralPath $python)) {
    Write-Host '[1/3] Creating project-local Python environment...'
    & python -m venv (Join-Path $PSScriptRoot '.venv')
    if ($LASTEXITCODE -ne 0) { throw 'Python environment creation failed. Install Python 3.12+.' }
}
# Apply the cache policy to every invocation of this project's Python,
# including direct pytest/check/benchmark commands and child processes.
$cachePolicy = @'
"""Generated by setup.ps1; keep this project's Python caches together."""
import os
import sys
from pathlib import Path

runtime = Path(sys.prefix).resolve().parent / '.runtime'
sys.pycache_prefix = str(runtime / 'python')
os.environ['PYTHONPYCACHEPREFIX'] = sys.pycache_prefix
cache_option = f'-o "cache_dir={(runtime / "pytest").as_posix()}"'
os.environ['PYTEST_ADDOPTS'] = (os.environ.get('PYTEST_ADDOPTS', '') + ' ' + cache_option).strip()
'@
Set-Content -LiteralPath (Join-Path $PSScriptRoot '.venv\Lib\site-packages\sitecustomize.py') -Value $cachePolicy -Encoding ASCII
if (-not $SkipInstall) {
    Write-Host '[1/3] Installing Python dependencies...'
    & $python -m pip install -r (Join-Path $PSScriptRoot 'requirements.txt')
    if ($LASTEXITCODE -ne 0) { throw 'Dependency installation failed. Check network access.' }
}
& $python -m backend.tools --write-reference
if ($LASTEXITCODE -ne 0) { throw 'Tool reference generation failed.' }
Write-Host '[2/3] Building KHyper C++ worker...'
if (-not (Get-Command cmake -ErrorAction SilentlyContinue)) { throw 'CMake 3.20+ is required.' }
# Arrow/Parquet libraries bundled by the Windows PyArrow wheel use the MSVC ABI.
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path -LiteralPath $vswhere)) { throw 'Visual Studio 2022 C++ tools are required for Arrow/Parquet.' }
$visualStudio = & $vswhere -latest -version '[17.0,18.0)' -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $visualStudio) { throw 'Install Visual Studio 2022 Desktop development with C++.' }
$buildDirectory = Join-Path $PSScriptRoot '.runtime\build'
& cmake -S $PSScriptRoot -B $buildDirectory -G 'Visual Studio 17 2022' -A x64 "-DPython3_EXECUTABLE=$($python.Replace('\', '/'))"
if ($LASTEXITCODE -ne 0) { throw 'CMake configuration failed. If switching compilers, clear .runtime/build first.' }
& cmake --build $buildDirectory --config Release --parallel 2
if ($LASTEXITCODE -ne 0) { throw 'C++ build failed.' }
Write-Host 'Setup complete. Run .\start.ps1, then select an external dataset descriptor.' -ForegroundColor Green
